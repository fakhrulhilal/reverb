namespace Reverb.Analysis.Tests;

public class CodegenTests(ITestOutputHelper output)
{
    string Generate(NotebookAnalysis a, string key)
    {
        var result = CellCodeGenerator.GenerateCell(a, key);
        foreach (var b in result.Blockers) output.WriteLine(b.ToString());
        Assert.True(result.Success);
        output.WriteLine(result.Code!.Source);
        return result.Code.Source;
    }

    [Fact]
    public void Generates_inputs_body_and_outputs()
    {
        var a = TestNotebooks.Analyze(["var orders = new List<Order> { new(1, 5) };\nvar threshold = 2.0;",
            "var big = orders.Where(o => o.Total >= threshold).ToList();\nConsole.WriteLine(big.Count);"],
            types: "record Order(int Id, double Total);");
        Assert.Equal("""
            // <auto-generated/>
            // Reverb cell 'c2'
            #pragma warning disable
            #nullable enable annotations
            #line 1 "cell:setup"
            using Reverb;
            using static Reverb.Notebook;
            #line default
            public static class __ReverbCell_c2
            {
                public static async global::System.Threading.Tasks.Task RunAsync(global::Reverb.Kernel.CellContext __ctx)
                {
                    var orders = __ctx.Store.Get<global::System.Collections.Generic.List<global::Order>?>("orders");
                    var threshold = __ctx.Store.Get<double>("threshold");
            #line 1 "cell:c2"
            var big = orders.Where(o => o.Total >= threshold).ToList();
            Console.WriteLine(big.Count);
            #line default
                    __ctx.Store.Set("big", big);
                }
            }

            """.ReplaceLineEndings("\n"), Generate(a, "c2"));
        Assert.Empty(CellCompiler.CompileAll(a));
    }

    [Fact]
    public void Types_cell_is_generated_with_internals_visible_to_cells()
    {
        var a = TestNotebooks.Analyze(["var o = new Order(1);"], types: "record Order(int Id);");
        var types = CellCodeGenerator.GenerateTypes(a);
        Assert.Contains("[assembly: global::System.Runtime.CompilerServices.InternalsVisibleTo(\"Reverb.Generated.Cells\")]\n#line 1 \"cell:types\"\nrecord Order(int Id);\n", types.Code!.Source);
        Assert.Empty(CellCompiler.CompileAll(a));
    }

    [Fact]
    public void Using_var_is_rewritten_without_moving_anything()
    {
        var a = TestNotebooks.Analyze([
            "using var ms = new MemoryStream(new byte[4]);\n  await using StreamWriter w = new(new MemoryStream()), w2 = new(new MemoryStream()); // two\nusing (var inner = new MemoryStream()) { }",
            "var len = ms.ReadByte();",
        ]);
        var code = Generate(a, "c1");
        Assert.Contains("\n      var ms = new MemoryStream(new byte[4]); __ctx.DisposeLater(ms);\n", code);
        Assert.Contains("\n              StreamWriter w = new(new MemoryStream()), w2 = new(new MemoryStream()); __ctx.DisposeLaterAsync(w); __ctx.DisposeLaterAsync(w2); // two\n", code);
        Assert.Contains("\nusing (var inner = new MemoryStream()) { }\n", code);
        Assert.Empty(CellCompiler.CompileAll(a));
    }

    [Fact]
    public void Local_functions_travel_as_delegates()
    {
        var a = TestNotebooks.Analyze(["var k = 3;", "int Twice(int v) => v * k;\nstatic void Log(string s) => Console.WriteLine(s);", "var t = Twice(2);\nLog(t.ToString());"]);
        var c2 = Generate(a, "c2");
        Assert.Contains("__ctx.Store.Set(\"Log\", (global::System.Action<string>)Log);", c2);
        Assert.Contains("__ctx.Store.Set(\"Twice\", (global::System.Func<int, int>)Twice);", c2);
        var c3 = Generate(a, "c3");
        Assert.Contains("var Twice = __ctx.Store.Get<global::System.Func<int, int>>(\"Twice\");", c3);
        Assert.Empty(CellCompiler.CompileAll(a));
    }

    [Fact]
    public void Args_come_from_the_context()
    {
        var a = TestNotebooks.Analyze(["var n = args.Length;"]);
        Assert.Contains("var args = __ctx.Args;", Generate(a, "c1"));
        Assert.Empty(CellCompiler.CompileAll(a));
    }

    [Fact]
    public void Keyword_names_are_escaped()
    {
        var a = TestNotebooks.Analyze(["var @class = 1;", "var y = @class + 1;"]);
        Assert.Contains("__ctx.Store.Set(\"class\", @class);", Generate(a, "c1"));
        Assert.Contains("var @class = __ctx.Store.Get<int>(\"class\");", Generate(a, "c2"));
        Assert.Empty(CellCompiler.CompileAll(a));
    }

    [Fact]
    public void Errors_block_generation()
    {
        var a = TestNotebooks.Analyze(["var q = new { A = 1 };", "var n = q.A;", "var fine = 1;"]);
        var blocked = CellCodeGenerator.GenerateCell(a, "c2");
        Assert.False(blocked.Success);
        Assert.Contains(blocked.Blockers, b => b.Id == RuleIds.AnonymousTypeShared);
        Assert.True(CellCodeGenerator.GenerateCell(a, "c3").Success);
    }

    [Fact]
    public void Setup_errors_block_every_cell()
    {
        var a = TestNotebooks.Analyze(["var x = 1;"], setup: "using Does.Not.Exist;");
        Assert.False(CellCodeGenerator.GenerateCell(a, "c1").Success);
    }

    [Fact]
    public void Async_cells_compile()
    {
        var a = TestNotebooks.Analyze(["var v = await Task.FromResult(41);", "await Task.Yield();\nvar w = v + 1;"]);
        Assert.False(a.HasErrors);
        Assert.Empty(CellCompiler.CompileAll(a));
    }
}
