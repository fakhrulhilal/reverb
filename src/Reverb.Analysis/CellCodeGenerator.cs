using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Reverb.Format;

namespace Reverb.Analysis;

public sealed record GeneratedCode(string CellKey, string ClassName, string Source);

/// <summary>Generated code, or the errors that stop the cell from being generated.</summary>
public sealed record CodegenResult(GeneratedCode? Code, ImmutableArray<NotebookDiagnostic> Blockers)
{
    public bool Success => Code is not null;
}

/// <summary>
/// Turns cells into the small programs the kernel runs. Each code cell becomes a static
/// <c>RunAsync(CellContext)</c> that reads its inputs from the value store, runs the cell's code
/// unchanged under <c>#line</c> mapping, and writes its outputs back.
/// </summary>
public static class CellCodeGenerator
{
    public const string CellsAssemblyName = "Reverb.Generated.Cells";
    public const string TypesAssemblyName = "Reverb.Generated.Types";
    public const string ContextType = "global::Reverb.Kernel.CellContext";
    public const string ContextParameter = "__ctx";

    /// <summary>Class names are per assembly and every cell has its own assembly, so this only needs to be a valid identifier.</summary>
    public static string ClassName(string key) => "__ReverbCell_" + key.Replace('-', '_');

    public static string FileName(string key) => $"cell:{key}";

    public static CodegenResult GenerateCell(NotebookAnalysis analysis, string key)
    {
        var cell = analysis.Cell(key) ?? throw new KeyNotFoundException($"There is no cell '{key}'.");
        if (cell.Kind != CellKind.Code) throw new ArgumentException($"Cell '{key}' is not a code cell.", nameof(key));

        var blockers = Blockers(analysis, cell);
        if (blockers.Length > 0) return new CodegenResult(null, blockers);

        var doc = analysis.Document.Cells[cell.Index];
        var layout = analysis.Layout.Cells[cell.Index];
        var source = RewriteUsingDeclarations(analysis, layout, doc.Source, cell.UsingDeclarations);

        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n");
        sb.Append($"// Reverb cell '{key}'\n");
        AppendPrologue(sb, analysis);
        sb.Append($"public static class {ClassName(key)}\n{{\n");
        sb.Append($"    public static async global::System.Threading.Tasks.Task RunAsync({ContextType} {ContextParameter})\n    {{\n");
        foreach (var input in cell.Inputs)
        {
            var name = Escape(input.Name);
            sb.Append(input.Kind == VariableKind.Args
                ? $"        var {name} = {ContextParameter}.Args;\n"
                : $"        var {name} = {ContextParameter}.Store.Get<{input.GeneratedType}>(\"{input.Name}\");\n");
        }
        sb.Append($"#line 1 \"{FileName(key)}\"\n");
        if (source.Length > 0) sb.Append(source).Append('\n');
        sb.Append("#line default\n");
        foreach (var output in cell.Stored)
        {
            var value = output.Kind == VariableKind.LocalFunction ? $"({output.GeneratedType}){Escape(output.Name)}" : Escape(output.Name);
            sb.Append($"        {ContextParameter}.Store.Set(\"{output.Name}\", {value});\n");
        }
        sb.Append("    }\n}\n");
        return new CodegenResult(new GeneratedCode(key, ClassName(key), sb.ToString()), []);
    }

    /// <summary>The types cell as its own assembly. Its types stay in the global namespace, like in the file.</summary>
    public static CodegenResult GenerateTypes(NotebookAnalysis analysis)
    {
        var types = analysis.Document.TypesCell;
        if (types is null) return new CodegenResult(null, []);
        var blockers = analysis.Diagnostics
            .Where(d => d.IsError && (d.CellKey is "types" or "setup" or null))
            .ToImmutableArray();
        if (blockers.Length > 0) return new CodegenResult(null, blockers);

        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n// Reverb types cell\n");
        AppendPrologue(sb, analysis);
        sb.Append($"[assembly: global::System.Runtime.CompilerServices.InternalsVisibleTo(\"{CellsAssemblyName}\")]\n");
        sb.Append($"#line 1 \"{FileName("types")}\"\n");
        if (types.Source.Length > 0) sb.Append(types.Source).Append('\n');
        sb.Append("#line default\n");
        return new CodegenResult(new GeneratedCode("types", "", sb.ToString()), []);
    }

    /// <summary>
    /// Errors that stop a cell from running: its own, the setup cell's, notebook-wide ones, and
    /// the types cell's when the cell uses notebook types.
    /// </summary>
    static ImmutableArray<NotebookDiagnostic> Blockers(NotebookAnalysis analysis, CellAnalysis cell) =>
        [.. analysis.Diagnostics.Where(d => d.IsError && (
            d.CellKey == cell.Key || d.CellKey == "setup" || d.CellKey is null || (d.CellKey == "types" && cell.UsesTypes)))];

    static void AppendPrologue(StringBuilder sb, NotebookAnalysis analysis)
    {
        // Diagnostics come from the analysis compilation, so generated code stays quiet.
        sb.Append("#pragma warning disable\n");
        sb.Append(analysis.Options.Nullable ? "#nullable enable annotations\n" : "#nullable disable\n");
        var setup = analysis.Document.SetupCell;
        if (setup is not null && setup.Source.Length > 0)
        {
            sb.Append($"#line 1 \"{FileName("setup")}\"\n");
            sb.Append(setup.Source).Append('\n');
            sb.Append("#line default\n");
        }
    }

    /// <summary>
    /// <c>using var x = e;</c> becomes <c>      var x = e; __ctx.DisposeLater(x);</c>. The keywords are
    /// blanked out rather than removed, so every line and column in the cell stays where it was.
    /// </summary>
    static string RewriteUsingDeclarations(NotebookAnalysis analysis, CellLayout layout, string source, ImmutableArray<UsingDeclaration> declarations)
    {
        if (declarations.IsEmpty) return source;
        var edits = new List<(int Offset, int Length, string Text)>();
        foreach (var d in declarations)
        {
            int Offset(int filePosition) => analysis.Map.ToSourceOffset(layout, source, filePosition);
            edits.Add((Offset(d.UsingKeyword.Start), d.UsingKeyword.Length, new string(' ', d.UsingKeyword.Length)));
            if (d.AwaitKeyword is { } aw) edits.Add((Offset(aw.Start), aw.Length, new string(' ', aw.Length)));
            var method = d.AwaitKeyword is null ? "DisposeLater" : "DisposeLaterAsync";
            var calls = string.Concat(d.Variables.Select(v => $" {ContextParameter}.{method}({Escape(v)});"));
            edits.Add((Offset(d.StatementEnd), 0, calls));
        }
        var sb = new StringBuilder(source);
        foreach (var (offset, length, text) in edits.OrderByDescending(e => e.Offset))
        {
            sb.Remove(offset, length);
            sb.Insert(offset, text);
        }
        return sb.ToString();
    }

    // Symbol names are always valid identifiers; only reserved keywords (written @class in source) need the @ back.
    static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
}
