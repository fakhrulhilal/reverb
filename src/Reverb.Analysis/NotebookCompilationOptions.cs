using System.Collections.Immutable;
using System.Reflection;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Reverb.Format;

namespace Reverb.Analysis;

/// <summary>The metadata references a notebook compiles against.</summary>
public sealed class ReferenceSet
{
    // The same file can be listed twice (the test host's trusted platform assemblies list
    // System.Private.CoreLib twice, for one). A compilation shrugs that off; a workspace project throws.
    ReferenceSet(ImmutableArray<MetadataReference> references) => References = [.. references.Distinct()];

    public ImmutableArray<MetadataReference> References { get; }

    /// <summary>
    /// The shared framework the current process runs on, plus the given assemblies (normally
    /// Reverb.Runtime and package assemblies). The kernel uses its own loaded assemblies the same way.
    /// </summary>
    public static ReferenceSet FromCurrentProcess(params Assembly[] extra)
    {
        var frameworkDir = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var tpa = ((string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? "").Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries);
        var framework = tpa
            .Where(p => string.Equals(Path.GetDirectoryName(p), frameworkDir, StringComparison.OrdinalIgnoreCase))
            .Select(p => (MetadataReference)CachedReference(p));
        var extras = extra.Select(a => (MetadataReference)CachedReference(a.Location));
        return new ReferenceSet([.. framework.Concat(extras)]);
    }

    public static ReferenceSet FromFiles(IEnumerable<string> paths) =>
        new([.. paths.Select(p => (MetadataReference)CachedReference(p))]);

    /// <summary>This set plus the given files (package assemblies, say).</summary>
    public ReferenceSet With(IEnumerable<string> paths) =>
        new(References.AddRange(paths.Select(p => (MetadataReference)CachedReference(p))));

    // Sharing PortableExecutableReference instances lets Roslyn reuse metadata across compilations.
    static readonly System.Collections.Concurrent.ConcurrentDictionary<string, PortableExecutableReference> cache = new(StringComparer.OrdinalIgnoreCase);

    static PortableExecutableReference CachedReference(string path) =>
        cache.GetOrAdd(path, p => MetadataReference.CreateFromFile(p));
}

/// <summary>
/// Compiler settings that match what <c>dotnet run file.cs</c> uses for a file-based app
/// (Debug, C# 14, nullable and implicit usings on, warning level 10), adjusted by any
/// <c>#:property</c> directives the notebook has.
/// </summary>
public sealed record NotebookCompilationOptions
{
    public const string ImplicitGlobalUsings = """
        // <auto-generated/>
        global using global::System;
        global using global::System.Collections.Generic;
        global using global::System.IO;
        global using global::System.Linq;
        global using global::System.Net.Http;
        global using global::System.Threading;
        global using global::System.Threading.Tasks;

        """;

    // DEBUG/TRACE come from the Debug configuration; the rest are the SDK's framework symbols for net10.0.
    static readonly ImmutableArray<string> PreprocessorSymbols =
    [
        "DEBUG", "TRACE", "NET", "NET10_0", "NETCOREAPP",
        "NET5_0_OR_GREATER", "NET6_0_OR_GREATER", "NET7_0_OR_GREATER", "NET8_0_OR_GREATER", "NET9_0_OR_GREATER", "NET10_0_OR_GREATER",
        "NETCOREAPP1_0_OR_GREATER", "NETCOREAPP1_1_OR_GREATER", "NETCOREAPP2_0_OR_GREATER", "NETCOREAPP2_1_OR_GREATER",
        "NETCOREAPP2_2_OR_GREATER", "NETCOREAPP3_0_OR_GREATER", "NETCOREAPP3_1_OR_GREATER",
    ];

    public LanguageVersion LanguageVersion { get; init; } = LanguageVersion.CSharp14;
    public bool Nullable { get; init; } = true;
    public bool ImplicitUsings { get; init; } = true;
    public bool AllowUnsafe { get; init; }
    public ImmutableArray<string> ExtraDefines { get; init; } = [];

    /// <summary>Problems with <c>#:property</c> values, reported against the notebook as a whole.</summary>
    public ImmutableArray<string> Problems { get; init; } = [];

    public static NotebookCompilationOptions FromDirectives(IEnumerable<Directive> directives)
    {
        var options = new NotebookCompilationOptions();
        var problems = new List<string>();
        foreach (var d in directives.Where(d => d.Kind == "property" && d.Value is not null))
        {
            var value = d.Value!.Trim();
            switch (d.Name.ToLowerInvariant())
            {
                case "langversion":
                    if (LanguageVersionFacts.TryParse(value, out var lv)) options = options with { LanguageVersion = lv };
                    else problems.Add($"'#:property LangVersion={value}' isn't a C# version this Reverb understands.");
                    break;
                case "nullable":
                    options = options with { Nullable = value.Equals("enable", StringComparison.OrdinalIgnoreCase) };
                    break;
                case "implicitusings":
                    options = options with { ImplicitUsings = value.Equals("enable", StringComparison.OrdinalIgnoreCase) || value.Equals("true", StringComparison.OrdinalIgnoreCase) };
                    break;
                case "allowunsafeblocks":
                    options = options with { AllowUnsafe = value.Equals("true", StringComparison.OrdinalIgnoreCase) };
                    break;
                case "defineconstants":
                    options = options with { ExtraDefines = [.. value.Split([';', ','], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Where(s => !s.StartsWith('$'))] };
                    break;
            }
        }
        return options with { Problems = [.. problems] };
    }

    public CSharpParseOptions ParseOptions => new CSharpParseOptions(LanguageVersion, preprocessorSymbols: PreprocessorSymbols.AddRange(ExtraDefines))
        .WithFeatures([new("FileBasedProgram", "true")]);

    public CSharpCompilationOptions CompilationOptions(OutputKind kind) => new(
        kind,
        nullableContextOptions: Nullable ? NullableContextOptions.Enable : NullableContextOptions.Disable,
        optimizationLevel: OptimizationLevel.Debug,
        allowUnsafe: AllowUnsafe,
        warningLevel: 10,
        specificDiagnosticOptions: [new("CS1701", ReportDiagnostic.Suppress), new("CS1702", ReportDiagnostic.Suppress)],
        deterministic: true);

    /// <summary>Global usings the SDK would generate, or empty when implicit usings are off.</summary>
    public string GlobalUsingsSource => ImplicitUsings ? ImplicitGlobalUsings : "";
}
